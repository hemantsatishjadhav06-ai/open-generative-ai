const BUNDLES = { en, zh };

function merge(base, override) {
  const out = { ...base };
  for (const [key, value] of Object.entries(override || {})) {
    out[key] = value && typeof value === "object" && !Array.isArray(value) ? merge(base[key] || {}, value) : value;
  }
  return out;
}

export function getAgentCopy(locale = "en") {
  if (!locale || locale === "en" || !BUNDLES[locale]) return en;
  return merge(en, BUNDLES[locale]);
}

// Locale-rooted app path for the agent pages: English lives at /agents/…,
// Chinese at /zh/agents/… (the host app mirrors the route tree per locale).
const LOCALE_ROOTS = { zh: "/zh" };

export function localePath(locale, path) {
  return `${LOCALE_ROOTS[locale] || ""}${path}`;
}
